export function setLang(l) { lang = S[l] ? l : "en"; }
export function getLang() { return lang; }
export function t(key, vars = {}) {
  const v = S[lang][key] ?? S.en[key] ?? key;
  if (typeof v !== "string") return v;
  return v.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ""));
}
